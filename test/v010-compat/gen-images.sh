#!/bin/bash
# Regenerates liblean-ftl-test/source/v010_images.h: regular areas formatted
# and written by lean-ftl v0.1.0, which the test suite (v010_compat_test)
# must still read. It builds harness.c against the v0.1.0 sources taken from
# git, generates the images, checks that the working tree reads each one,
# and prints them as C. Deterministic: running it again on the same sources
# gives the same header.
set -e
cd "$(dirname "$0")/../.."
OUT=liblean-ftl-test/source/v010_images.h
TAG=v0.1.0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

git show $TAG:liblean-ftl/source/ftl.c > $TMP/ftl.c
git show $TAG:liblean-ftl/include/lean-ftl.h > $TMP/lean-ftl.h
COMMIT=$(git rev-parse --short "$TAG^{commit}")
gcc -O1 -I$TMP -DLFTL_V010 -DGIT_VERSION=$TAG -DVERSION_TIMESTAMP=0 -DBUILD_TYPE=x \
  test/v010-compat/harness.c $TMP/ftl.c -o $TMP/h010
gcc -O1 -Wall -Wextra -Wno-unused-parameter -Iliblean-ftl/include \
  -DGIT_VERSION=head -DVERSION_TIMESTAMP=0 -DBUILD_TYPE=x \
  test/v010-compat/harness.c liblean-ftl/source/ftl.c -o $TMP/hhead

# The geometries of liblean-ftl-test/include/type.h (write unit, page):
# STM32U5, STM32L5, CH32V307 and the Linux build. The images are made for
# the test's nvmd area: data of 4 write units, 2 slots.
GEOS=("16 8192" "8 2048" "2 4096")
# name:writes:erase_all. The writes are those of harness.c's do_write():
# whole, aligned part, transaction, unaligned, whole... With 2 slots, 4
# writes leave the newest version in slot 0 and 5 in slot 1, the other slot
# holding the version before.
IMAGES=("format:0:0" "one_write:1:0" "four_writes:4:0" "five_writes:5:0" "erase_all:2:1")

{
  echo "//Generated by test/v010-compat/gen-images.sh from lean-ftl $TAG ($COMMIT), do not edit."
  echo "//Regular areas formatted and written by lean-ftl $TAG, each as the runs of"
  echo "//programmed write units of the area (offset, size, bytes): everything else"
  echo "//reads erased. v010_compat_test rebuilds them and reads them back."
  echo "#pragma once"
  echo "#include <stdint.h>"
  echo
  echo "typedef struct {"
  echo "  uint32_t offset;"
  echo "  uint32_t size;"
  echo "  const uint8_t*bytes;"
  echo "} v010_run_t;"
  echo
  echo "typedef struct {"
  echo "  const char*name;"
  echo "  uint32_t write_size;"
  echo "  uint32_t erase_size;"
  echo "  uint32_t data_size;"
  echo "  uint32_t area_size;"
  echo "  uint32_t slot;          //the slot $TAG had current"
  echo "  uint32_t n_runs;"
  echo "  const v010_run_t*runs;"
  echo "  const uint8_t*expected; //data_size bytes, what $TAG read back"
  echo "} v010_image_t;"
  echo
  for g in "${GEOS[@]}"; do
    set -- $g
    ws=$1; es=$2; ds=$((4*ws)); ns=2
    echo "#if (LFTL_WU_SIZE == $ws) && (LFTL_PAGE_SIZE == $es)"
    entries=""
    n=0
    for spec in "${IMAGES[@]}"; do
      IFS=: read -r name nw ea <<<"$spec"
      img=$TMP/${name}_${ws}_${es}
      $TMP/h010 gen $ws $es $ds $ns $nw $ea $img >/dev/null
      # the working tree must read it: same data, same slot, no erase or program
      chk=$($TMP/hhead chk $ws $es $ds $ns 1 $img)
      case "$chk" in
        *"scan_erases=0 scan_writes=0"*) ;;
        *) echo "working tree does not read $img: $chk" >&2; exit 1;;
      esac
      $TMP/h010 emit $name $ws $es $ds $ns $img
      entries="$entries  V010_ENTRY_$name,\n"
      n=$((n+1))
    done
    echo "static const v010_image_t v010_images[] = {"
    printf "$entries"
    echo "};"
    echo "#define V010_N_IMAGES $n"
    echo "#endif"
    echo
  done
  echo "#ifndef V010_N_IMAGES"
  echo "#warning \"no lean-ftl $TAG images for this geometry: add it to test/v010-compat/gen-images.sh and run it\""
  echo "#define V010_N_IMAGES 0"
  echo "static const v010_image_t v010_images[1];"
  echo "#endif"
} > $TMP/out.h
mv $TMP/out.h $OUT
echo "wrote $OUT"
